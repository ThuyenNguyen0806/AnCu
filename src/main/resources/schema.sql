CREATE TABLE IF NOT EXISTS NguoiDung (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 cccd VARCHAR(12) NOT NULL UNIQUE CHECK (cccd ~ '^[0-9]{12}$'),
 phone VARCHAR(15) NOT NULL,
 email VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS NhaO (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(20) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 type VARCHAR(10) NOT NULL CHECK (type IN ('VILLA','RESORT')),
 address VARCHAR(255) NOT NULL,
 area NUMERIC(12,2) NOT NULL CHECK (area > 0),
 price NUMERIC(19,0) NOT NULL CHECK (price > 0),
 status VARCHAR(30) NOT NULL CHECK (status IN ('Sẵn bán','Đã đặt chỗ','Đã bán')),
 rooms INT NOT NULL CHECK (rooms > 0),
 image INT NOT NULL DEFAULT 0,
 description VARCHAR(2000)
);
CREATE TABLE IF NOT EXISTS BietThuNhaVuon (
 houseId BIGINT PRIMARY KEY REFERENCES NhaO(id),
 garden NUMERIC(12,2) NOT NULL CHECK (garden >= 0),
 pool NUMERIC(12,2) NOT NULL CHECK (pool >= 0)
);
CREATE TABLE IF NOT EXISTS KhuNghiDuong (
 houseId BIGINT PRIMARY KEY REFERENCES NhaO(id),
 amenities INT NOT NULL CHECK (amenities >= 0)
);
CREATE TABLE IF NOT EXISTS DangKy (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customerId BIGINT NOT NULL REFERENCES NguoiDung(id),
 houseId BIGINT NOT NULL REFERENCES NhaO(id),
 date DATE NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('Chờ duyệt','Đã duyệt','Đã hủy')),
 note VARCHAR(1000)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_DangKy_Approved ON DangKy(houseId) WHERE status='Đã duyệt';
CREATE TABLE IF NOT EXISTS LichHen (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customerId BIGINT NOT NULL REFERENCES NguoiDung(id),
 houseId BIGINT NOT NULL REFERENCES NhaO(id),
 date DATE NOT NULL,
 time TIME(0) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('Chờ xác nhận','Đã xác nhận','Hoàn thành','Đã hủy')),
 note VARCHAR(1000) NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_LichHen_Date ON LichHen(date,time);
